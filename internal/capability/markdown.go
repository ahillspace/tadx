package capability

import (
	"bytes"
	"fmt"
	"strings"
)

// GenerateMarkdown renders the deterministic public capability reference.
func GenerateMarkdown(definitions []Definition) ([]byte, error) {
	if err := Validate(definitions); err != nil {
		return nil, fmt.Errorf("validate capability registry: %w", err)
	}
	definitions = append([]Definition(nil), definitions...)
	definitions = sorted(definitions)

	var output bytes.Buffer
	output.WriteString("<!-- Code generated by cmd/gencapdocs. DO NOT EDIT. -->\n\n")
	output.WriteString("# Capability reference\n\n")
	output.WriteString("This reference derives from the executable capability registry.\n")
	output.WriteString("Use `tadx capability get <id>` for the same focused metadata at runtime.\n\n")
	output.WriteString("## Capability summary\n\n")
	output.WriteString("| Capability ID | Owner | Disposition | Verification | Implementation | Command |\n")
	output.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, definition := range definitions {
		if definition.Disposition == DispositionDelegated {
			continue
		}
		fmt.Fprintf(&output, "| `%s` | %s | %s | %s | %s | %s |\n",
			escapeTable(definition.ID), escapeTable(string(definition.Owner)), escapeTable(string(definition.Disposition)),
			escapeTable(string(definition.Verification)), escapeTable(string(definition.Implementation)), escapeTable(command(definition)))
	}
	output.WriteString("\n## Out of scope\n\nThese capabilities are outside TADX; no command or automatic handoff is provided.\n\n")
	for _, definition := range definitions {
		if definition.Disposition == DispositionDelegated {
			fmt.Fprintf(&output, "- `%s`: %s\n", definition.ID, escapeProse(definition.Outcome))
		}
	}
	output.WriteString("\n## Capability definitions\n\n")
	for _, definition := range definitions {
		if definition.Disposition == DispositionDelegated {
			continue
		}
		fmt.Fprintf(&output, "### `%s`\n\n", definition.ID)
		fmt.Fprintf(&output, "%s\n\n", escapeProse(definition.Outcome))
		fields := [][2]string{
			{"Surface", escapeProse(definition.Surface)},
			{"Operation type", string(definition.Type)},
			{"Owner", string(definition.Owner)},
			{"Selectors", escapeProse(definition.Selectors)},
			{"Products and availability", escapeProse(definition.Availability)},
			{"Product disposition", string(definition.Disposition)},
			{"Evidence level", string(definition.EvidenceLevel)},
			{"Verification readiness", string(definition.Verification)},
			{"Implementation state", string(definition.Implementation)},
			{"Local write", yesNo(definition.LocalWrite)},
			{"Remote mutation", yesNo(definition.RemoteMutation)},
			{"Administrative", yesNo(definition.Administrative)},
			{"Supports `--preview`", yesNo(definition.SupportsPreview)},
			{"Supports `--batch-file`", yesNo(definition.SupportsBatch)},
			{"Raw capable", yesNo(definition.RawCapable)},
			{"Safety and guard", escapeProse(definition.SafetyGuard)},
			{"Artifact effect", escapeProse(definition.ArtifactEffect)},
			{"Upstream operation", escapeProse(definition.Upstream)},
			{"Evidence", escapeProse(definition.Evidence)},
			{"Validation or blocker", escapeProse(definition.Validation)},
			{"Blocker ID", emptyAsNone(string(definition.Blocker))},
			{"Command binding", command(definition)},
		}
		for _, field := range fields {
			fmt.Fprintf(&output, "- %s: %s\n", field[0], field[1])
		}
		output.WriteByte('\n')
	}
	return bytes.TrimSuffix(output.Bytes(), []byte("\n")), nil
}

func sorted(definitions []Definition) []Definition {
	result := make([]Definition, len(definitions))
	for index, definition := range definitions {
		result[index] = clone(definition)
	}
	// All registry callers use the same stable ordering implementation.
	return sortDefinitions(result)
}

func sortDefinitions(definitions []Definition) []Definition {
	for current := 1; current < len(definitions); current++ {
		for previous := current; previous > 0 && definitions[previous].ID < definitions[previous-1].ID; previous-- {
			definitions[previous], definitions[previous-1] = definitions[previous-1], definitions[previous]
		}
	}
	return definitions
}

func command(definition Definition) string {
	if len(definition.CommandPath) == 0 {
		return "None"
	}
	if len(definition.CommandPath) == 1 && definition.CommandPath[0] == "tadx" {
		return "`tadx`"
	}
	return "`tadx " + strings.Join(definition.CommandPath, " ") + "`"
}

func escapeTable(value string) string { return strings.ReplaceAll(value, "|", "\\|") }

// escapeProse keeps placeholders such as <name> visible instead of letting
// markdown viewers treat them as HTML tags.
func escapeProse(value string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(value)
}
func emptyAsNone(value string) string {
	if value == "" {
		return "None"
	}
	return value
}
func yesNo(value bool) string {
	if value {
		return "Yes"
	}
	return "No"
}
