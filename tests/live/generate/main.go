// Command generate maintains the opt-in Go test entry points from the catalog.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"

	"github.com/ahillspace/tadx/tests/live"
)

func main() {
	catalog, err := live.Catalog()
	if err != nil {
		panic(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n//go:build livecli\n\npackage live_test\n\nimport (\"flag\"; \"fmt\"; \"os\"; \"testing\"; \"github.com/ahillspace/tadx/tests/live\")\n\n")
	b.WriteString("func TestMain(m *testing.M) { if !flag.Parsed() {flag.Parse()}; if flag.Lookup(\"test.run\").Value.String()==\"\" {fmt.Fprintln(os.Stderr,\"livecli tests require an explicit -run selector\");os.Exit(2)};os.Exit(m.Run()) }\n")
	b.WriteString("func runSelected(t *testing.T,id string){t.Helper();r,err:=live.RunFromEnvironment(t.Context(),id);if err!=nil{t.Fatalf(\"%s: %v\",id,err)};if len(r.Results)!=1||r.Results[0].Status!=\"passed\"{t.Fatalf(\"selected contract did not pass: %+v\",r.Results)}}\n")
	for _, spec := range catalog {
		fmt.Fprintf(&b, "func %s(t *testing.T){runSelected(t,%q)}\n", spec.GoName, spec.ID)
	}
	source, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("livecli_generated_test.go", source, 0o644); err != nil {
		panic(err)
	}
}
